<#
.SYNOPSIS
    Writes Options/Window/Changelog.lua, the options window's copy of the newest _Packaging/Changelog.md entry.

.DESCRIPTION
    The Overview of the options window lists what changed in the version the player runs, in English
    (docs/work/2026-10-25-options-revamp, decision 3a). The file is generated at release time, not kept in step by
    every PR: the release gate (.claude/release-gate.ps1) runs this script with -Check and fails while the file is not
    the changelog's top entry. Each line keeps its words and its sub-bullets; Markdown code marks and the maintainer's
    "(dev note: ...)" asides are left out, since the Overview is a short list.

.PARAMETER Check
    Compare instead of writing: prints the version and exits 0 when the file is current, exits 1 with the reason when not.
#>
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$repo = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$changelog = Join-Path $repo '_Packaging\Changelog.md'
$target = Join-Path $repo 'Options\Window\Changelog.lua'

function Remove-DevNote([string]$text) {
    while (($start = $text.IndexOf('(dev note:')) -ge 0) {
        $depth = 0
        $end = $text.Length - 1
        for ($i = $start; $i -lt $text.Length; $i++) {
            if ($text[$i] -eq '(') { $depth++ }
            elseif ($text[$i] -eq ')') { $depth--; if ($depth -eq 0) { $end = $i; break } }
        }
        $text = $text.Remove($start, $end - $start + 1)
    }
    (($text -replace '`', '') -replace '\s{2,}', ' ').Trim()
}

function ConvertTo-LuaString([string]$text) {
    '"' + (($text -replace '\\', '\\') -replace '"', '\"') + '"'
}

# The top entry: its version, then its ### parts with their bullets
$version = $null
$parts = [System.Collections.Generic.List[object]]::new()
$part = $null
foreach ($line in Get-Content -LiteralPath $changelog -Encoding UTF8) {
    if ($line -match '^## (\S+)') {
        if ($version) { break }
        $version = $Matches[1]
        continue
    }
    if (-not $version) { continue }
    if ($line -match '^### (.+)$') {
        $part = [pscustomobject]@{ Heading = $Matches[1].Trim(); Lines = [System.Collections.Generic.List[string]]::new() }
        $parts.Add($part)
        continue
    }
    if (-not $part) { continue }
    if ($line -match '^[-*] (.+)$') {
        $text = Remove-DevNote $Matches[1]
        if ($text) { $part.Lines.Add("- $text") }
    } elseif ($line -match '^\s+[-*] (.+)$') {
        $text = Remove-DevNote $Matches[1]
        if ($text) { $part.Lines.Add("    - $text") }
    } elseif ($line.Trim() -and $part.Lines.Count -gt 0) {
        $part.Lines[$part.Lines.Count - 1] = ($part.Lines[$part.Lines.Count - 1] + ' ' + (Remove-DevNote $line.Trim())).Trim()
    }
}
if (-not $version) { throw "No '## <version>' entry in $changelog" }

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('local _, addon = ...')
$out.Add('')
$out.Add('-- Generated by .claude/tools/Build-ChangelogLua.ps1 from the top entry of _Packaging/Changelog.md, at release time;')
$out.Add('-- the release gate fails while it is stale. The options window''s Overview lists it, in English.')
$out.Add('addon.Options.Window.Changelog = {')
$out.Add("    Version = $(ConvertTo-LuaString $version),")
$out.Add('    Parts = {')
foreach ($p in $parts) {
    if ($p.Lines.Count -eq 0) { continue }
    $out.Add("        { Heading = $(ConvertTo-LuaString $p.Heading), Lines = {")
    foreach ($l in $p.Lines) { $out.Add("            $(ConvertTo-LuaString $l),") }
    $out.Add('        } },')
}
$out.Add('    },')
$out.Add('}')
$text = $out -join "`r`n"

if ($Check) {
    $current = if (Test-Path -LiteralPath $target) { [IO.File]::ReadAllText($target) } else { '' }
    if ($current -ceq $text) {
        "Options/Window/Changelog.lua lists $version"
        exit 0
    }
    "Options/Window/Changelog.lua is not the changelog's $version entry; run .claude/tools/Build-ChangelogLua.ps1 and commit the file"
    exit 1
}
[IO.File]::WriteAllText($target, $text, (New-Object Text.UTF8Encoding $false))
"Wrote Options/Window/Changelog.lua for $version ($(@($parts | ForEach-Object { $_.Lines.Count } | Measure-Object -Sum).Sum) lines)"